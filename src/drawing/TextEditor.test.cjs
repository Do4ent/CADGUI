const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const ts = require('typescript'), React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
function load(file) {
  const output = ts.transpileModule(fs.readFileSync(file, 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022}}).outputText;
  const exports = {};
  vm.runInNewContext(output, {exports, structuredClone, require(id) {
    if (id.endsWith('.css')) return {};
    if (!id.startsWith('.')) return require(id);
    const target = path.resolve(path.dirname(file), id);
    const filename = fs.existsSync(target + '.tsx') ? target + '.tsx' : fs.existsSync(target + '.ts') ? target + '.ts' : path.join(target, 'index.ts');
    return load(filename);
  }});
  return exports;
}
const {formatTextRange, replaceTextRange, updateParagraphText, TextEditor} = load(path.join(__dirname, 'TextEditor.tsx'));
const plain = value => JSON.parse(JSON.stringify(value));
const runs = [{text: 'Текст '}, {text: '⌀10', format: {italic: true}}, {text: ' кг', field: {kind: 'model', key: 'mass', targetId: 'part-1'}}];
const original = structuredClone(runs);
const changed = plain(formatTextRange(runs, 1, 4, {}, {bold: true}));
assert.equal(changed.map(run => run.text).join(''), 'Текст ⌀10 кг');
assert.equal(changed[1].text, 'екс');
assert.equal(changed[1].format.bold, true);
assert.deepEqual(plain(runs), original, 'formatting must not mutate source');
const fieldFormatted = plain(formatTextRange(runs, 9, 10, {}, {underline: true}));
assert.equal(fieldFormatted.at(-1).field.targetId, 'part-1', 'field remains typed and atomic');
assert.equal(fieldFormatted.at(-1).format.underline, true);
const inserted = plain(replaceTextRange(runs, 0, 0, '±'));
assert.equal(inserted.map(run => run.text).join(''), '±Текст ⌀10 кг');
assert.equal(inserted.at(-1).field.targetId, 'part-1');
const paragraph = {runs, align: 'right', list: 'number', listStart: 3};
const updated = plain(updateParagraphText(paragraph, 'Текст ⌀20 кг'));
assert.equal(updated.runs.map(run => run.text).join(''), 'Текст ⌀20 кг');
assert.equal(updated.runs.at(-1).field.key, 'mass', 'editing ordinary text preserves untouched fields');
assert.equal(updated.align, 'right');
assert.equal(updated.listStart, 3);
assert.deepEqual(plain(runs), original);
const cleared = plain(updateParagraphText(paragraph, ''));
assert.equal(cleared.runs.map(run => run.text).join(''), '');
assert.equal(cleared.runs.some(run => run.field), false);
const entity = {id: 'text-1', kind: 'text', name: 'Заметка', x: 10, y: 20, width: 50, height: 20, rotation: 0, styleId: 'standard', overrides: {}, paragraphs: [{runs: [{text: '<script>alert(1)</script> Привет ⌀±'}]}]};
const before = structuredClone(entity);
let confirms = 0;
const markup = renderToStaticMarkup(React.createElement(TextEditor, {entity, styles: [], onConfirm() {confirms++;}, onCancel() {}}));
assert.match(markup, /Редактор текста чертежа/);
assert.match(markup, /Абзац 1/);
assert.match(markup, /Высота текста/);
assert.match(markup, /Маска фона/);
assert.match(markup, /aria-labelledby=/);
assert.match(markup, /&lt;script&gt;/, 'plain user text is escaped');
assert.doesNotMatch(markup, /<script>/);
assert.equal(confirms, 0);
assert.deepEqual(entity, before, 'opening a draft must not mutate the source');
console.log('PASS: drawing text fragment edits, field preservation, draft isolation and editor SSR');
