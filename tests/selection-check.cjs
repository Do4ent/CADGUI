const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
function load(name) {
  const exports = {};
  const source = fs.readFileSync(`${__dirname}/../src/selection/${name}.ts`, 'utf8');
  vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports });
  return exports;
}
const s = load('selectionModel'), v = load('visibilityModel');
const json = value => JSON.parse(JSON.stringify(value));
const equal = (actual, expected) => assert.deepEqual(json(actual), json(expected));
const ids = ['a', 'b', 'c', 'd'];
let state = s.selectItem(s.emptySelection, 'b', ids);
equal(state, { selectedIds: ['b'], anchorId: 'b' });
state = s.selectItem(state, 'd', ids, 'range');
equal(state.selectedIds, ['b', 'c', 'd']);
equal(s.selectItem(state, 'a', ids, 'range').selectedIds, ['a', 'b']);
equal(s.selectItem({ selectedIds: ['gone'], anchorId: 'gone' }, 'c', ids, 'range'), { selectedIds: ['c'], anchorId: 'c' });
assert.equal(s.selectItem(state, 'missing', ids), state);
equal(s.selectItem(state, 'c', ids, 'toggle').selectedIds, ['b', 'd']);
equal(s.selectItem({ selectedIds: ['a'], anchorId: 'c' }, 'd', ids, 'add-range').selectedIds, ['a', 'c', 'd']);
equal(s.pruneSelection({ selectedIds: ['a', 'a', 'gone'], anchorId: 'gone' }, ids), { selectedIds: ['a'], anchorId: null });
assert.equal(s.selectionMode({ shiftKey: true, metaKey: true }), 'add-range');
assert.equal(s.selectionMode({ ctrlKey: true }), 'toggle');
assert.equal(s.selectionMode({ shiftKey: true }), 'range');
assert.equal(s.selectionMode({}), 'replace');
equal(s.selectItems(s.emptySelection, ['d', 'b', 'b', 'gone'], ids), { selectedIds: ['b', 'd'], anchorId: 'd' });
equal(s.selectItems(state, ['c', 'a'], ids, 'toggle').selectedIds, ['b', 'd', 'a']);
equal(s.selectItems(state, [], ids), s.emptySelection);
const original = { present: [{ id: 'a', visible: true }, { id: 'b', visible: false }, { id: 'c', visible: true }], past: [], future: [] };
const hidden = v.changeVisibility(original, ['a', 'c'], 'hide');
equal(hidden.present.map(x => x.visible), [false, false, false]);
assert.equal(hidden.past.length, 1);
equal(original.present.map(x => x.visible), [true, false, true]);
const undone = v.undoVisibility(hidden);
equal(undone.present, json(original.present));
equal(v.redoVisibility(undone).present, json(hidden.present));
assert.equal(v.changeVisibility(undone, ['missing'], 'hide'), undone);
assert.equal(v.changeVisibility(original, [], 'isolate'), original);
assert.equal(v.changeVisibility(original, ['missing'], 'isolate'), original);
equal(v.changeVisibility(original, ['b'], 'isolate').present.map(x => x.visible), [false, true, false]);
equal(v.changeVisibility(original, [], 'show-all').present.map(x => x.visible), [true, true, true]);
assert.equal(v.changeVisibility(undone, ['b'], 'show').future.length, 0);
assert.equal(v.undoVisibility(original), original);
assert.equal(v.redoVisibility(original), original);
console.log('PASS selection ranges, modifiers, box sets, pruning, immutable visibility and undo/redo');
